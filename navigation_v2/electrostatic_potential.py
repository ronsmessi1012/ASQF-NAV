"""
Electrostatic-Inspired Dynamic Potential Field.

Implements an artificial repulsive potential and force inspired by electrostatic repulsion:
    U_ij(d) = k_ij / 2 * (1/d - 1/L_ij)^2   for 0 < d < L_ij, else 0
    F_ij = k_ij * (1/d_ij - 1/L_ij) * r_ij / d_ij^3 for 0 < d_ij < L_ij, else 0

Note: This is a mathematical navigation analogy and does not represent physical electric charges.
Includes full numerical stability: epsilon clamping, force clipping, coincident position handling,
and no NaN/Inf guarantees.
"""

from typing import List, Optional, Tuple, Union
import numpy as np

from navigation_v2.config import AQSFConfigV2
from navigation_v2.dynamic_entities import MovingObstacle


def electrostatic_potential_scalar(
    distance: Union[float, np.ndarray],
    influence_radius: float,
    k: float,
    min_epsilon: float = 1e-4
) -> Union[float, np.ndarray]:
    """
    Compute scalar potential U_ij(d) = k / 2 * (1/d - 1/L)^2 for 0 < d < L, 0 otherwise.
    Safe against division-by-zero.
    """
    is_scalar = np.isscalar(distance)
    d = np.asarray(distance, dtype=float)

    # Clamping distance to avoid division by zero
    d_clamped = np.maximum(d, min_epsilon)

    # Influence mask
    mask = (d < influence_radius) & (d >= 0.0)

    # U(d) = 0.5 * k * (1/d - 1/L)^2
    term = (1.0 / d_clamped) - (1.0 / influence_radius)
    potential = np.where(mask, 0.5 * k * (term ** 2), 0.0)

    if is_scalar:
        return float(potential.item())
    return potential


def electrostatic_force_vector(
    p_i: np.ndarray,
    q_j: np.ndarray,
    influence_radius: float,
    k: float,
    min_epsilon: float = 1e-4,
    max_force_clip: float = 30.0,
    fallback_direction: Optional[np.ndarray] = None
) -> np.ndarray:
    """
    Compute repulsive force F_ij = -nabla_{p_i} U_ij.
    Analytical expression:
        F_ij = k * (1/d_ij - 1/L_ij) * r_ij / d_ij^3  for 0 < d_ij < L_ij, else 0
    where r_ij = p_i - q_j.
    """
    p = np.asarray(p_i, dtype=float)
    q = np.asarray(q_j, dtype=float)
    r = p - q
    d = np.linalg.norm(r)

    # Outside influence radius: zero force
    if d >= influence_radius:
        return np.zeros(2, dtype=float)

    # Coincident or near-coincident handling
    if d < min_epsilon:
        if fallback_direction is not None and np.linalg.norm(fallback_direction) > 1e-8:
            direction = fallback_direction / np.linalg.norm(fallback_direction)
        else:
            # Deterministic pseudo-random fallback direction
            direction = np.array([1.0, 0.0], dtype=float)
        return direction * max_force_clip

    # Normal calculation
    d_clamped = max(d, min_epsilon)
    term = (1.0 / d_clamped) - (1.0 / influence_radius)
    force = k * term * (r / (d_clamped ** 3))

    # Finite force clipping
    force_magnitude = np.linalg.norm(force)
    if force_magnitude > max_force_clip:
        force = (force / force_magnitude) * max_force_clip

    # Sanity checks: NaN / Inf prevention
    if not np.all(np.isfinite(force)):
        force = np.zeros(2, dtype=float)

    return force


def compute_dynamic_field_grid(
    X: np.ndarray,
    Y: np.ndarray,
    robot_positions: np.ndarray,
    moving_obstacles: List[MovingObstacle],
    current_robot_idx: Optional[int] = None,
    config: Optional[AQSFConfigV2] = None
) -> np.ndarray:
    """
    Compute the 2D scalar potential field grid generated by dynamic entities:
        F_dynamic(X, Y) = sum U_robot + sum U_moving_obstacle
    Applies grid singularity clamping (d* = max(d, static_singularity_clamp = 0.5))
    consistent with v1 field generation to avoid discrete pixel delta singularities.
    """
    if config is None:
        config = AQSFConfigV2()

    field_dynamic = np.zeros_like(X, dtype=float)
    grid_clamp = config.static_singularity_clamp  # 0.5

    # 1. Other robots
    if robot_positions is not None and len(robot_positions) > 0:
        robot_safety_dist = config.compute_robot_safety_distance()
        robot_influence = config.compute_influence_distance(robot_safety_dist)

        for idx, pos in enumerate(robot_positions):
            if current_robot_idx is not None and idx == current_robot_idx:
                continue
            rx, ry = pos[0], pos[1]
            dist_grid = np.sqrt((X - rx) ** 2 + (Y - ry) ** 2)
            u_grid = electrostatic_potential_scalar(
                dist_grid,
                influence_radius=robot_influence,
                k=config.k_robot,
                min_epsilon=grid_clamp
            )
            field_dynamic += u_grid

    # 2. Moving obstacles
    if moving_obstacles:
        for obs in moving_obstacles:
            ox, oy = obs.position[0], obs.position[1]
            obs_safety_dist = config.compute_safety_distance(obs.radius)
            obs_influence = config.compute_influence_distance(obs_safety_dist)
            dist_grid = np.sqrt((X - ox) ** 2 + (Y - oy) ** 2)
            u_grid = electrostatic_potential_scalar(
                dist_grid,
                influence_radius=obs_influence,
                k=config.k_obstacle,
                min_epsilon=grid_clamp
            )
            field_dynamic += u_grid

    return field_dynamic


def compute_dynamic_repulsive_force(
    p_i: np.ndarray,
    robot_idx: int,
    all_robot_positions: np.ndarray,
    moving_obstacles: List[MovingObstacle],
    config: Optional[AQSFConfigV2] = None
) -> np.ndarray:
    """
    Compute total analytical repulsive force for robot i:
        F_dynamic_i = sum F_robot_repulsion + sum F_moving_obstacle_repulsion
    """
    if config is None:
        config = AQSFConfigV2()

    total_force = np.zeros(2, dtype=float)

    # 1. Other robots
    if all_robot_positions is not None:
        robot_safety_dist = config.compute_robot_safety_distance()
        robot_influence = config.compute_influence_distance(robot_safety_dist)

        for j, pos in enumerate(all_robot_positions):
            if j == robot_idx:
                continue
            # Deterministic fallback direction based on index difference if coincident
            fallback = np.array([np.cos(j * 1.57), np.sin(j * 1.57)])
            f_ij = electrostatic_force_vector(
                p_i,
                pos,
                influence_radius=robot_influence,
                k=config.k_robot,
                min_epsilon=config.min_distance_epsilon,
                max_force_clip=config.max_force_clip,
                fallback_direction=fallback
            )
            total_force += f_ij

    # 2. Moving obstacles
    if moving_obstacles:
        for obs in moving_obstacles:
            obs_safety_dist = config.compute_safety_distance(obs.radius)
            obs_influence = config.compute_influence_distance(obs_safety_dist)
            fallback = np.array([1.0, 0.0])
            f_io = electrostatic_force_vector(
                p_i,
                obs.position,
                influence_radius=obs_influence,
                k=config.k_obstacle,
                min_epsilon=config.min_distance_epsilon,
                max_force_clip=config.max_force_clip,
                fallback_direction=fallback
            )
            total_force += f_io

    return total_force
