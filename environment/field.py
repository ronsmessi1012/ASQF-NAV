import numpy as np


# ============================================================
# ENVIRONMENT PARAMETERS
# ============================================================

GRID_SIZE = 16

GOAL_GAIN = 1.0
OBSTACLE_GAIN = 80.0
AGENT_GAIN = 30.0

OBSTACLE_INFLUENCE = 3.0
AGENT_INFLUENCE = 2.5

EPSILON = 1e-6


# ============================================================
# DISTANCE FUNCTION
# ============================================================

def distance_field(X, Y, point):
    """
    Calculate Euclidean distance from every grid point
    to a given point.
    """

    px, py = point

    return np.sqrt(
        (X - px) ** 2 +
        (Y - py) ** 2
    )


# ============================================================
# GOAL ATTRACTION
# ============================================================

def goal_potential(X, Y, goal):
    """
    Attractive potential toward the goal.
    """

    gx, gy = goal

    return 0.5 * GOAL_GAIN * (
        (X - gx) ** 2 +
        (Y - gy) ** 2
    )


# ============================================================
# OBSTACLE REPULSION
# ============================================================

def obstacle_potential(X, Y, obstacles):
    """
    Repulsive potential generated by obstacles.
    """

    potential = np.zeros_like(X, dtype=float)

    for obstacle in obstacles:

        distance = distance_field(
            X,
            Y,
            obstacle
        )

        influence = distance < OBSTACLE_INFLUENCE

        safe_distance = np.maximum(
        distance,
        0.5
        )


        repulsion = 0.5 * OBSTACLE_GAIN * (
            1.0 / safe_distance
            - 1.0 / OBSTACLE_INFLUENCE
        ) ** 2

        potential += np.where(
            influence,
            repulsion,
            0.0
        )

    return potential


# ============================================================
# AGENT REPULSION
# ============================================================

def agent_potential(X, Y, agents, current_agent):
    """
    Repulsive potential generated by other agents.
    """

    potential = np.zeros_like(X, dtype=float)

    for i, agent in enumerate(agents):

        if i == current_agent:
            continue

        distance = distance_field(
            X,
            Y,
            agent
        )

        influence = distance < AGENT_INFLUENCE

        safe_distance = np.maximum(
            distance,
            0.5
        )

        repulsion = 0.5 * AGENT_GAIN * (
            1.0 / safe_distance
            - 1.0 / AGENT_INFLUENCE
        ) ** 2

        potential += np.where(
            influence,
            repulsion,
            0.0
        )

    return potential


# ============================================================
# COMPLETE POTENTIAL FIELD
# ============================================================

def generate_field(
    agents,
    goals,
    obstacles,
    current_agent
):
    """
    Generate the complete APF field for one agent.

    F = Goal Attraction
        + Obstacle Repulsion
        + Agent Repulsion
    """

    x = np.arange(GRID_SIZE)
    y = np.arange(GRID_SIZE)

    X, Y = np.meshgrid(
        x,
        y,
        indexing="xy"
    )

    goal = goals[current_agent]

    F_goal = goal_potential(
        X,
        Y,
        goal
    )

    F_obstacle = obstacle_potential(
        X,
        Y,
        obstacles
    )

    F_agent = agent_potential(
        X,
        Y,
        agents,
        current_agent
    )

    F_total = (
        F_goal
        + F_obstacle
        + F_agent
    )

    return X, Y, F_total